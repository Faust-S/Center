// A read-only navigation projection of the ORIGINAL signed Task and ACCEPT.
// Never use a truncated catalog summary, editable draft or matching title.
// This does not publish a Result to Atlas, confer rights, or apply a change.
import {readOriginalResultReview} from '../runtime/cen03-d3-owner.mjs';
import {validateReviewDecisionReceipt} from '../runtime/cen03-review-continuation.mjs';
const id='[A-Za-z0-9][A-Za-z0-9._:/@-]{0,159}';
const draftLine=new RegExp('^Черновик Center: ('+id+'), редакция ([1-9][0-9]*)\\.$');
const workLine=new RegExp('^Ссылка на проект Atlas: ('+id+') @ (0|[1-9][0-9]*), работа ('+id+')$');
const resultLine=new RegExp('^Источник принятого Result: '+id+' @ [a-f0-9]{64}, Result [a-f0-9]{64}, приёмка '+id+'$');
/** @typedef {{organizationId:string,workspaceId:string,taskId:string,taskRevisionId:string,
 * resultRevisionId:string,acceptanceId:string,packageSha256:string,actorId:string,operationId:string,draftId:string,
 * draftEditNumber:number,workRef:{projectId:string,workId:string,revision:string},
 * resultExcerpt:string,resultTruncated:boolean}} AcceptedAtlasFocus */
/** @typedef {Omit<AcceptedAtlasFocus,'resultExcerpt'|'resultTruncated'>} AcceptedAtlasReturn */
/** @typedef {{organizationId:string,workspaceId:string,taskId:string,taskRevisionId:string,resultRevisionId:string,acceptanceId:string,applicationRevisionIds?:ReadonlyArray<string>}} AppliedResultReference */
/** @typedef {{description:string,source:AppliedResultReference,atlas?:{ref:{projectId:string,workId:string,revision:string},view:any},originalD3?:boolean}} AppliedResultDraftSelection */
/** Extract only the existing footer generated by prepareEmployeeDraftTask.
 * An original Task may have no Atlas WorkRef. Never invent one. */
export function signedAssignmentAtlasWork(text){
 if(typeof text!=='string'||!text.length||text.length>10000)return null;
 const parts=text.trim().split('\n\n');
 if(resultLine.test(parts.at(-1)??''))parts.pop();
 const work=workLine.exec(parts.at(-1)??'');
 const draft=draftLine.exec(parts.at(-2)??'');
 if(!work||!draft||parts.length<3||
    !Number.isSafeInteger(Number(work[2]))||!Number.isSafeInteger(Number(draft[2])))return null;
 return {draftId:draft[1],draftEditNumber:Number(draft[2]),
  workRef:{projectId:work[1],revision:work[2],workId:work[3]}};
}
/** @returns {AcceptedAtlasFocus|null} */
export function acceptedAtlasFocus({preview,receipt,session,packageSha256,operationId}){
 const acceptance=validateReviewDecisionReceipt(receipt,session,packageSha256,operationId,'ACCEPT');
 if(acceptance.found!==true)return null;
 const signed=readOriginalResultReview(preview,session.organizationId,session.workspaceId);
 if(!signed||signed.packageSha256!==packageSha256)return null;
 const source=signedAssignmentAtlasWork(signed.assignmentText);
 if(!source)return null;
 const excerpt=Array.from(signed.resultText).slice(0,500).join('');
 return Object.freeze({...source,organizationId:session.organizationId,workspaceId:session.workspaceId,
  taskId:signed.taskId,taskRevisionId:signed.taskRevisionId,resultRevisionId:signed.resultRevisionId,
  acceptanceId:acceptance.receipt.acceptanceId,packageSha256,actorId:session.actorId,operationId,
  resultExcerpt:excerpt,resultTruncated:signed.resultLength>excerpt.length});
}
// Return navigation retains IDs only, never the Result content, owner session
// credentials or a substitute receipt. The new live owner verifies it again.
/** @param {AcceptedAtlasFocus} source @returns {AcceptedAtlasReturn} */
export function acceptedAtlasReturnPointer(source){
 const {resultExcerpt,resultTruncated,...ids}=source;
 return Object.freeze({...ids,workRef:Object.freeze({...ids.workRef})});
}
/** @param {AcceptedAtlasReturn|null} source @param {any} session */
export function acceptedAtlasScopeMatches(source,session){
 return !!source&&source.organizationId===session?.organizationId&&
  source.workspaceId===session?.workspaceId&&source.actorId===session?.actorId;
}
/** @param {AcceptedAtlasReturn|null} a @param {AcceptedAtlasReturn|null} b */
export function sameAcceptedAtlasSource(a,b){
 return !!a&&!!b&&[
  'organizationId','workspaceId','actorId','operationId','packageSha256',
  'taskId','taskRevisionId','resultRevisionId','acceptanceId','draftId','draftEditNumber'
 ].every(key=>a[key]===b[key])&&['projectId','workId','revision']
  .every(key=>a.workRef[key]===b.workRef[key]);
}
// Select the identical work (including when the plan has advanced), never a
// neighbouring project/item. Historical source revision remains unchanged.
/** @param {{projects:Array<{id:string,workItems:Array<{id:string}>}>,revision:string}} view
 * @param {{projectId:string,workId:string,revision:string}} ref */
export function selectAcceptedAtlasWork(view,ref){
 const project=view.projects.find(p=>p.id===ref.projectId);
 if(!project)return {projectId:'',workId:'',status:'PROJECT_MISSING_IN_SOURCE'};
 const work=project.workItems.find(w=>w.id===ref.workId);
 if(!work)return {projectId:project.id,workId:'',status:'WORK_MISSING_IN_SOURCE'};
 return {projectId:project.id,workId:work.id,
  status:view.revision===ref.revision?'SOURCE_REVISION_MATCHES':'SOURCE_REVISION_CHANGED'};
}
